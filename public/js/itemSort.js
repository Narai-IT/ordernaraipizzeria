// office-server ส่งรายการมาตาม sort_order (ลำดับแถวในชีท item) ก่อนแล้วค่อยรหัส ในหมวดเดียวกันจึงกระโดด
// คนหาของด้วยรหัสอ่านยาก — เรียงตามรหัสในหน้าเว็บเอง ลำดับหมวดยังเป็นแบบเดิม (หมวดที่เจอก่อนขึ้นก่อน)
// เทียบแบบตัวเลข: '100102' มาก่อน '1000002' ไม่ใช่เทียบทีละตัวอักษร

export const byItemCode = (a, b) =>
  String(a.code ?? '').localeCompare(String(b.code ?? ''), 'en', { numeric: true });

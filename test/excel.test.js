// การอ่านรหัสสินค้าจากไฟล์ Excel ของหน้าตั้งรายการที่ร้านเบิกได้
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { codesFromRows, normCode } from '../public/js/excelCodes.js';

test('ไฟล์ที่ดาวน์โหลดจากหน้านี้: เอาเฉพาะแถวที่คอลัมน์ "เบิกได้" ใส่ Y', () => {
  const rows = [
    ['รหัสสินค้า', 'ชื่อสินค้า', 'หน่วย', 'หมวดสโตร์', 'เบิกได้'],
    ['100101', 'แป้ง', 'ก้อน', 'แป้ง', 'Y'],
    ['100102', 'แป้งเล็ก', 'ก้อน', 'แป้ง', ''],
    ['100201', 'ชีส', 'กก.', 'ชีส', 'y'],
    ['100202', 'พาร์มีซาน', 'กก.', 'ชีส', '1'],
  ];
  assert.deepEqual(codesFromRows(rows), { codes: ['100101', '100201', '100202'], mode: 'flag' });
});

test('ไฟล์รายการเฉย ๆ: มีหัวอยู่แถวไหนก็ได้ ใช้ทุกรหัสในคอลัมน์ที่หัวว่า รหัส', () => {
  const rows = [
    ['รายการเบิกสาขา SUM', ''],
    ['', ''],
    ['ลำดับ', 'รหัส', 'ชื่อ'],
    ['1', '100101', 'แป้ง'],
    ['2', '100101', 'ซ้ำ'],
    ['3', '', 'แถวว่าง'],
    ['4', '100601', 'กล่อง'],
  ];
  assert.deepEqual(codesFromRows(rows), { codes: ['100101', '100601'], mode: 'list' });
});

test('ไม่มีหัวเลย: ใช้คอลัมน์ A และข้ามข้อความที่ไม่ใช่รหัส', () => {
  assert.deepEqual(codesFromRows([['100101'], ['หมายเหตุ'], ['100102']]).codes, ['100101', '100102']);
});

test('normCode: ตัด .0 ที่ Excel เติมและ 0 นำหน้า', () => {
  assert.equal(normCode('0100101'), '100101');
  assert.equal(normCode('100101.0'), '100101');
  assert.equal(normCode(' AB12 '), 'ab12');
});
